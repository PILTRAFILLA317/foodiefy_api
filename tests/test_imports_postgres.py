def enqueue(store,owner,cfg,key=None):
    return store.submit(owner,key or str(uuid4()),{'url':'https://example.org/owned-test'},policy_hash(cfg))


def bearer(cfg,user):
    return {'Authorization':'Bearer '+jwt.encode({'sub':str(user),'aud':'authenticated','iss':cfg.SUPABASE_URL+'/auth/v1',
             'role':'authenticated','iat':int(time.time()),'exp':int(time.time())+60},cfg.SUPABASE_JWT_SECRET.get_secret_value(),algorithm='HS256')}


def test_real_api_two_users_idempotency_and_cancel(local):
    store,admin,(a,b),cfg=local
    with TestClient(create_app(cfg)) as client:
        ah= dict(bearer(cfg,a),**{'Idempotency-Key':str(uuid4())})
        response=client.post('/v1/imports',headers=ah,json={'url':'https://example.org/owned-test'})
        assert response.status_code==202,response.json()
        job=response.json()['job_id']
        assert client.post('/v1/imports',headers=ah,json={'url':'https://example.org/owned-test'}).json()['job_id']==job
        assert client.post('/v1/imports',headers=ah,json={'url':'https://example.org/changed'}).status_code==409
        assert client.get('/v1/imports/'+job,headers=bearer(cfg,b)).status_code==404
        assert client.post('/v1/imports/'+job+'/cancel',headers=bearer(cfg,b)).status_code==404
        assert client.get('/v1/imports',headers=bearer(cfg,b)).json()['items']==[]
        assert client.get('/health/ready').status_code==200
        assert client.post('/v1/imports/'+job+'/cancel',headers=ah).json()['status']=='canceled'
        assert client.get('/v1/imports/'+job,headers=ah).json()['stage'] is None


