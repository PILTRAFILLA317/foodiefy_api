def worker_fakes(local,tmp_path,*,visual=False):
    store,admin,users,cfg=local
    cfg=cfg.model_copy(update={'ENABLE_VISUAL_FALLBACK':visual})
    counts={'source':0,'media':0,'stt':0,'extract':0}
    b=EvidenceBundle(canonical_url='https://example.org/owned-test',platform='youtube',source_type='social_video')
    b.description=fragment('description','cantidades en pantalla' if visual else 'Mezclar ingredientes')
    b=finalize(b)
    ref=EvidenceBundle(canonical_url='https://example.org',platform='web',source_type='webpage')
    parse_html((Path(__file__).parent/'fixtures/acquisition/simple.html').read_bytes(),ref)
    answer=direct_json_ld(ref)
    class Resolver:
        def __init__(self,**kw): self.stage=kw['on_stage']
        def resolve(self,url):
            counts['source']+=1
            self.stage('extracting_metadata')
            return b
    class Media:
        def __init__(self,*a,**kw): pass
        @contextmanager
        def audio(self,evidence):
            counts['media']+=1
            path=tmp_path/'owned.mp3'
            path.write_bytes(b'ID3-owned-synthetic-test')
            try:
                yield AudioEvidence(path,2)
            finally:
                path.unlink(missing_ok=True)
    class STT:
        def __init__(self,config,session): self.session=session
        def transcribe(self,evidence):
            def invoke():
                counts['stt']+=1
                return {'text':'Mezclar'},StageUsage(stage='stt',provider='openai',model='gpt-transcribe',latency_ms=1,duration_seconds=2)
            data=self.session.execute('stt','openai','gpt-transcribe',.001,invoke)
            return TranscriptResult(text=data['text'],languages=['es'],duration_seconds=2,mime_type='audio/mpeg',size_bytes=10,content_hash='owned',usage=self.session.stages[-1])
    class Extract:
        def __init__(self,config,session,stage): self.session,self.stage=session,stage
        def extract(self,evidence):
            assert evidence.transcript is not None
            assert evidence.bundle.description.text==b.description.text
            def invoke():
                counts['extract']+=1
                if counts['extract']==1:
                    raise PipelineError('provider_transient_error',transient=True)
                result=answer.model_copy(deep=True)
                if visual:
                    result=partial('missing_visual')
                    result.visual_evidence_required=True
                    result.visual_evidence_reasons=['on_screen_quantities']
                return result.model_dump(mode='json'),StageUsage(stage=self.stage,provider='openai',model='gpt-5-nano',latency_ms=1,input_tokens=10,output_tokens=10)
            data=self.session.execute(self.stage,'openai','gpt-5-nano',.001,invoke)
            return type(answer).model_validate(data)
    return cfg,counts,dict(resolver_factory=Resolver,media_factory=Media,transcriber_factory=STT,extractor_factory=Extract)


def test_stt_persisted_after_extractor_failure_reused_on_new_worker(local,tmp_path):
    store,admin,users,_=local
    cfg,counts,factories=worker_fakes(local,tmp_path)
    row=enqueue(store,users[0],cfg)
    assert Worker(cfg,**factories).run_once()
    assert store.get(users[0],row['id'])['status']=='queued'
    assert counts['stt']==1 and counts['extract']==1
    admin.execute('update foodiefy_imports.jobs set next_attempt_at=now() where id=%s',(row['id'],))
    assert Worker(cfg,**factories).run_once()
    assert store.get(users[0],row['id'])['status']=='succeeded'
    assert counts=={'source':1,'media':1,'stt':1,'extract':2}
    entries=admin.execute('select operation,count(*) as n from foodiefy_imports.usage_ledger where job_id=%s group by operation',(row['id'],)).fetchall()
    assert {r['operation']:r['n'] for r in entries}=={'source':1,'stt':1,'text_extraction':2}
    assert admin.execute('select count(*) as n from foodiefy_imports.artifacts where job_id=%s',(row['id'],)).fetchone()['n']==0


def test_visual_quota_exhausted_never_recharges_stt(local,tmp_path):
    store,admin,users,_=local
    cfg,counts,factories=worker_fakes(local,tmp_path,visual=True)
    # Exercise SQL quota directly after successful STT and cached transcript.
    row=enqueue(store,users[0],cfg)
    Worker(cfg,**factories).run_once()
    admin.execute('update foodiefy_imports.controls set daily_visual=0')
    admin.execute('update foodiefy_imports.jobs set next_attempt_at=now() where id=%s',(row['id'],))
    class VisualMedia(factories['media_factory']):
        @contextmanager
        def visual(self,evidence):
            from src.analysis.models import VisualEvidence
            path=tmp_path/'owned-frame.jpg'
            path.write_bytes(b'owned-test-not-provider-input')
            try:
                yield VisualEvidence(evidence,(path,),'frames',2,(0,))
            finally:
                path.unlink(missing_ok=True)
    class Visual:
        def __init__(self,config,session):
            self.session=session
        def extract(self,evidence):
            return self.session.execute('visual','gemini','gemini-2.5-flash',.001,lambda:pytest.fail('visual provider must not be called'))
    factories['visual_factory']=Visual
    factories['media_factory']=VisualMedia
    Worker(cfg,**factories).run_once()
    result=store.get(users[0],row['id'])
    assert result['error_code']=='visual_required_unavailable'
    assert counts['stt']==1
    assert admin.execute("select count(*) as n from foodiefy_imports.usage_ledger where job_id=%s and operation='stt'",(row['id'],)).fetchone()['n']==1


